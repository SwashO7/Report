#!/usr/bin/env node
/**
 * Suraksha Labs — one-command stack launcher.
 *
 * `bun run up` (or `node scripts/up.mjs`) does everything needed to get the
 * full app (Postgres + API + web, behind nginx) running from a clean clone:
 *
 *   1. Generates a root .env with strong random secrets on first run
 *      (idempotent — never overwrites an existing .env or its values).
 *   2. Builds and starts docker-compose.prod.yml.
 *   3. Waits for the API's health/readiness endpoint.
 *   4. Prints the URL to open.
 *
 * Same command on a laptop or a fresh server VM: `bun run up`.
 * Stop everything: `bun run down`. Tail logs: `bun run logs`.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(repoRoot, '.env');

function b64url(bytes) {
  return randomBytes(bytes).toString('base64url');
}

function ensureEnvFile() {
  if (existsSync(envPath)) {
    console.log('[up] .env already exists — leaving it untouched.');
    return;
  }

  const appUrl = process.env.SURAKSHA_APP_URL ?? 'http://localhost';
  const apiUrl = process.env.SURAKSHA_API_URL ?? appUrl;
  const webPort = process.env.SURAKSHA_WEB_PORT ?? '80';

  const contents = `# Generated by scripts/up.mjs on ${new Date().toISOString()}
# Safe to edit. Never commit this file (already in .gitignore).

# Public URLs — change these if the box has a real domain.
APP_URL=${appUrl}
API_URL=${apiUrl}
WEB_PORT=${webPort}

# Postgres (container-internal network only, not published).
POSTGRES_USER=suraksha
POSTGRES_PASSWORD=${b64url(24)}
POSTGRES_DB=suraksha

# Session + flag secrets — unique per install, generated automatically.
SESSION_SECRET=${b64url(48)}
FLAG_HMAC_SECRET=${b64url(32)}

# Optional: Google OAuth (leave blank to disable the button).
GOOGLE_CLIENT_ID=
GOOGLE_CLIENT_SECRET=

# Optional: SMTP (leave blank to log emails to the API console instead).
SMTP_HOST=
SMTP_PORT=587
SMTP_USER=
SMTP_PASS=
EMAIL_FROM=Suraksha Labs <no-reply@surakshalabs.example>
`;

  writeFileSync(envPath, contents, { encoding: 'utf8' });
  console.log('[up] Generated .env with fresh random secrets.');
}

function readEnvValue(key) {
  const raw = readFileSync(envPath, 'utf8');
  const match = raw.match(new RegExp(`^${key}=(.*)$`, 'm'));
  return match ? match[1].trim() : '';
}

function run(cmd, args) {
  console.log(`[up] $ ${cmd} ${args.join(' ')}`);
  const result = spawnSync(cmd, args, { cwd: repoRoot, stdio: 'inherit', shell: false });
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}

function composeAvailable() {
  const probe = spawnSync('docker', ['compose', 'version'], { stdio: 'ignore', shell: false });
  return probe.status === 0;
}

async function waitForHealth(apiUrl, timeoutMs = 90_000) {
  const deadline = Date.now() + timeoutMs;
  const url = `${apiUrl.replace(/\/$/, '')}/api/v1/health/ready`;
  while (Date.now() < deadline) {
    try {
      const res = await fetch(url);
      if (res.ok) return true;
    } catch {
      // API not accepting connections yet — retry.
    }
    await new Promise((r) => setTimeout(r, 2000));
  }
  return false;
}

async function main() {
  if (!composeAvailable()) {
    console.error('[up] Docker Compose v2 not found. Install Docker Desktop (or docker-ce + compose plugin) first.');
    process.exit(1);
  }

  ensureEnvFile();

  run('docker', ['compose', '-f', 'docker-compose.prod.yml', 'up', '-d', '--build']);

  const apiUrl = readEnvValue('API_URL') || 'http://localhost';
  console.log('[up] Waiting for the API to become ready...');
  const healthy = await waitForHealth(apiUrl);
  if (!healthy) {
    console.error('[up] API did not report ready within 90s. Check logs: bun run logs');
    process.exit(1);
  }
  console.log('[up] API is up and the database is reachable.');

  const webPort = readEnvValue('WEB_PORT') || '80';
  const appUrl = readEnvValue('APP_URL') || 'http://localhost';
  const displayUrl = webPort === '80' ? appUrl : `${appUrl}:${webPort}`;

  console.log('');
  console.log('==================================================');
  console.log(`  Suraksha Labs is live: ${displayUrl}`);
  console.log('  Logs:  bun run logs');
  console.log('  Stop:  bun run down');
  console.log('==================================================');
}

main();
